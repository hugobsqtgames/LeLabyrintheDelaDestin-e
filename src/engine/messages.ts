/**
 * Message du moteur dans la langue du contenu, paramètres remplacés.
 * Repli : table française, puis la clé elle-même.
 */
export function msg(content: GameContent, key: string, params?: Record<string, string | number>): string {
  const template = content.messages?.[key] ?? MESSAGES_FR[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}

/** Variante singulier/pluriel : `${base}.one` jusqu'à 1, `${base}.many` au-delà. */
export function msgCount(content: GameContent, base: string, n: number, params?: Record<string, string | number>): string {
  return msg(content, `${base}.${n > 1 ? 'many' : 'one'}`, { n, ...params });
}

/** Paragraphes communs décrivant le sort des compagnons dans les épilogues. */
function epilogueCompagnons(): { text: string; if?: Condition }[] {
  return [
    { text: 'Maëlle a pris en charge l’infirmerie du pont inférieur dès le premier soir. Elle ne dort toujours pas beaucoup. Mais quand elle dort, elle dort.', if: MAELLE_ICI },
    { text: 'Maëlle n’est pas là. Sa lampe s’est éteinte au fond d’une galerie de l’ossuaire, et parfois, la nuit, Théo la cherche encore des yeux sur le pont.', if: all(companionIs('maelle', 'dead'), THEO_ICI) },
    { text: 'Inès a recopié le carnet de son frère à l’encre, page après page, pour que personne ne puisse dire qu’il n’a pas existé.', if: INES_ICI },
    { text: 'Nour a demandé à voir les cages vides de la cale. Elle les a regardées longtemps, puis elle a demandé qu’on les jette par-dessus bord. On l’a fait.', if: NOUR_ICI },
    { text: 'Kaz tient la barre du pont arrière, la nuit. Il chante en polonais pour les enfants qui ne dorment pas. Il chante faux. Personne ne s’en plaint.', if: all(KAZ_ICI, notFlag('kaz_sacrifice')) },
  ];
}

function mareeScene(voie: 'accord' | 'force'): Scene {
  const fin = voie === 'accord' ? 'c4_fin_accord' : 'c4_fin_capitaines';
  return {
    id: `c4_maree_${voie}`,
    chapter: C,
    location: 'ecluse',
    title: 'La marée',
    kind: 'story',
    checkpoint: true,
    text: [
      p('C’est le bruit qui les a attirés. Les cris, les moteurs, les tirs peut-être. Sur le chemin de halage, en amont, une marée grise s’avance entre les peupliers : des centaines de Muets, en silence, avec ce cliquetis immense, comme une pluie de grêle sur un toit de tôle.'),
      p('Pour quitter l’écluse, la Destinée doit descendre dans le bassin et attendre que les portes aval s’ouvrent. Mais le courant électrique est coupé depuis l’aube, et les vannes se manœuvrent à la main, depuis la maison de l’éclusier, au bord du chemin. Là où la horde arrivera en premier.'),
      p('Douze minutes de manivelle. Quelqu’un doit rester.'),
      say('kaz', '« C’est mon métier, ça. » Kaz retrousse ses manches. « Trente ans que je tourne des manivelles d’écluse. Je sais faire ça les yeux fermés. »', all(KAZ_ICI, relMin('kaz', 4))),
      p('À la tête de la marée avance une silhouette énorme, en tenue anti-émeute noire, casque et jambières. Le Colosse. Il marche droit vers la maison de l’éclusier.'),
    ],
    onEnter:
      voie === 'force'
        ? [when(THEO_GASPARD, [companion('theo', 'companion'), rel('theo', 3), journal('Vous avez libéré Théo du camion de Gaspard.')]), set('voie_force')]
        : [set('voie_accord')],
    choices: [
      {
        id: 'cloche',
        text: 'Grimper sur la passerelle et faire sonner la cloche du Berger pour emmener la horde loin du fleuve.',
        kind: 'item',
        requires: [has('cloche_berger')],
        effects: [set('cloche_utilisee'), xp(60), journal('La cloche du Berger a emmené la horde loin de l’écluse.')],
        next: fin,
      },
      {
        id: 'kaz',
        text: 'Laisser Kaz prendre la manivelle.',
        kind: 'sacrifice',
        visibleIf: [KAZ_ICI, relMin('kaz', 4)],
        warning: 'Kaz ne reviendra pas.',
        effects: [companion('kaz', 'dead'), set('kaz_sacrifice'), journal('Kaz est resté à la manivelle de l’écluse. Il n’est pas revenu.')],
        next: fin,
      },
      {
        id: 'moi',
        text: 'Prendre vous-même la manivelle.',
        kind: 'sacrifice',
        warning: 'Vous ne monterez pas à bord.',
        next: 'c4_fin_gardien',
      },
      {
        id: 'colosse',
        text: 'Tenir le chemin devant la maison de l’éclusier, face au Colosse, pendant qu’on tourne la manivelle.',
        kind: 'fight',
        warning: 'Combat de boss. Une défaite serait fatale.',
        next: `c4_colosse_${voie}`,
      },
    ],
  };
}

